"""📁 Past tickets (FR-07, Support): browse, filter and export the historical ticket dataset."""
import streamlit as st

from app import backend, state, ui
from src.taxonomy import CATEGORIES, ENVIRONMENTS, SERVICES, TEAMS, WHO_AFFECTED

state.require_role("support")
ui.page_header("📁", "Past tickets",
               "Browse the historical tickets: filter them, open one to see every field, and export what you see.")

PRIORITIES = list(ui.PRIORITY_COLOR)          # P1..P4, same order as the colours used everywhere
ALL_SUBCATEGORIES = [s for subs in CATEGORIES.values() for s in subs]

# (session key, dataset column, label, options)
FILTERS = [
    ("pt_service", "service", "Service", list(SERVICES)),
    ("pt_category", "category", "Category", list(CATEGORIES)),
    ("pt_subcategory", "subcategory", "Subcategory", None),     # options depend on the chosen categories
    ("pt_priority", "priority", "Priority", PRIORITIES),
    ("pt_team", "team", "Team", TEAMS),
    ("pt_environment", "environment", "Environment", ENVIRONMENTS),
    ("pt_who_affected", "who_affected", "Who affected", WHO_AFFECTED),
]

FIELD_LABELS = {
    "ticket_id": "Ticket ID", "service": "Service", "environment": "Environment",
    "who_affected": "Who affected", "user_category": "Category the user chose",
    "user_subcategory": "Subcategory the user chose", "category": "Category (label)",
    "subcategory": "Subcategory (label)", "team": "Team", "symptom_type": "Symptom type",
    "impact": "Impact", "urgency": "Urgency", "priority": "Priority",
}


def _clear_filters() -> None:
    for key, *_ in FILTERS:
        st.session_state[key] = []
    st.session_state["pt_text"] = ""


def _subcategory_options() -> list[str]:
    chosen = st.session_state.get("pt_category") or []
    return [s for c in chosen for s in CATEGORIES[c]] if chosen else ALL_SUBCATEGORIES


# Drop chosen subcategories that no longer belong to the chosen categories (before the widget is drawn).
_sub_opts = _subcategory_options()
if st.session_state.get("pt_subcategory"):
    st.session_state["pt_subcategory"] = [s for s in st.session_state["pt_subcategory"] if s in _sub_opts]

# ── Filters ─────────────────────────────────────────────────────────────────
with st.container(border=True):
    row1 = st.columns(4)
    row2 = st.columns(4)
    for col, (key, _, label, options) in zip(row1 + row2, FILTERS):
        col.multiselect(label, options if options is not None else _sub_opts, key=key, placeholder="Any")
    row2[3].text_input("Search", key="pt_text", placeholder="Words in the description or a ticket ID")
    c1, c2 = st.columns([5, 1], vertical_alignment="center")
    c1.caption("Date and status filters aren't available: the dataset has no date or status fields.")
    c2.button("Clear filters", on_click=_clear_filters, width="stretch")

filters = {col: st.session_state.get(key) or [] for key, col, _, _ in FILTERS}
filters["text"] = (st.session_state.get("pt_text") or "").strip()

try:
    df = backend.list_tickets(filters, role=state.role())
except Exception as e:  # noqa: BLE001 - friendly message, never a traceback
    ui.show_error(e)
    st.stop()

st.caption("**Generated labels** — the categories, team, impact, urgency and priority in this dataset "
           "were generated by us for the hackathon, not taken from a real service desk.")

if df.empty:
    ui.empty_state("No tickets match these filters — clear a filter to see more.")
    st.stop()

# ── Summary: counts by priority for the filtered set ────────────────────────
counts = df["priority"].value_counts()
for col, p in zip(st.columns(len(PRIORITIES)), PRIORITIES):
    ui.kpi(col, f"{p} tickets", f"{int(counts.get(p, 0)):,}")

# ── Table ───────────────────────────────────────────────────────────────────
top_l, top_r = st.columns([4, 1], vertical_alignment="bottom")
top_l.markdown(f"**{len(df):,} tickets** match these filters. Select a row to see its details.")
top_r.download_button("Export filtered CSV", df.to_csv(index=False).encode("utf-8"),
                      file_name="resolveiq_past_tickets.csv", mime="text/csv",
                      width="stretch", help="Personal data in descriptions is already masked.")

event = st.dataframe(
    df,
    key="pt_table",
    hide_index=True,
    width="stretch",
    on_select="rerun",
    selection_mode="single-row",
    column_order=["ticket_id", "priority", "description", "service", "category", "subcategory",
                  "team", "environment", "who_affected", "symptom_type", "impact", "urgency"],
    column_config={
        "ticket_id": st.column_config.TextColumn("Ticket", width="small"),
        "priority": st.column_config.TextColumn("Priority", width="small"),
        "description": st.column_config.TextColumn("Description", width="large",
                                                   help="Personal data is masked."),
        "service": st.column_config.TextColumn("Service"),
        "category": st.column_config.TextColumn("Category"),
        "subcategory": st.column_config.TextColumn("Subcategory"),
        "team": st.column_config.TextColumn("Team"),
        "environment": st.column_config.TextColumn("Environment"),
        "who_affected": st.column_config.TextColumn("Who affected"),
        "symptom_type": st.column_config.TextColumn("Symptom type"),
        "impact": st.column_config.TextColumn("Impact", width="small"),
        "urgency": st.column_config.TextColumn("Urgency", width="small"),
    },
)

# ── Detail card for the selected row ────────────────────────────────────────
rows = event.selection.rows if event is not None else []
if rows and rows[0] < len(df):
    t = df.iloc[rows[0]].to_dict()
    with st.container(border=True):
        st.markdown(f"#### {t['ticket_id']} &nbsp; {ui.priority_badge(t['priority'])}")
        st.markdown(f"> {t['description']}")
        if (t.get("user_category"), t.get("user_subcategory")) != (t.get("category"), t.get("subcategory")):
            ui.chips([(f"User chose {t.get('user_category')} › {t.get('user_subcategory')}, "
                       f"label is {t.get('category')} › {t.get('subcategory')}", "orange")])
        fields = [k for k in FIELD_LABELS if k != "ticket_id" and k in t]
        left, right = st.columns(2)
        half = (len(fields) + 1) // 2
        for col, keys in ((left, fields[:half]), (right, fields[half:])):
            for k in keys:
                value = ui.priority_badge(t[k]) if k == "priority" else (t[k] if t[k] not in (None, "") else "—")
                col.markdown(f"**{FIELD_LABELS[k]}:** {value}")
        st.caption("Generated labels — created by us for the hackathon dataset.")
else:
    st.caption("No ticket selected.")
